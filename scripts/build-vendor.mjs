#!/usr/bin/env node
// Builds app/runtime/vendor/{react,react-dom-client,htm,htm-react}.mjs (one shared React
// instance via esbuild code splitting) and copies the Geist fonts into app/runtime/fonts/.
import { build } from "esbuild";
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync, copyFileSync, rmSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

process.env.NODE_ENV = "production";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const entriesDir = join(root, "scripts", "vendor-entries");
const outdir = join(root, "app", "runtime", "vendor");
const fontsDir = join(root, "app", "runtime", "fonts");

const ident = (k) => /^[A-Za-z_$][\w$]*$/.test(k) && k !== "default";

/** Named re-exports for a CJS module, enumerated from the module itself so the list is complete. */
function namedExports(mod, from, local) {
  const keys = Object.keys(require(mod)).filter(ident).sort();
  return `export const {\n  ${keys.join(",\n  ")}\n} = ${local};\n`;
}

mkdirSync(entriesDir, { recursive: true });
const header = "// Generated by scripts/build-vendor.mjs. Do not edit.\n";
const entries = {
  "react": header + `import React from "react";\nexport default React;\n` + namedExports("react", "react", "React"),
  "react-dom-client":
    header + `import ReactDOMClient from "react-dom/client";\nexport default ReactDOMClient;\n` +
    namedExports("react-dom/client", "react-dom/client", "ReactDOMClient"),
  "htm": header + `import htm from "htm";\nexport default htm;\n`,
  "htm-react":
    header + `import htm from "htm";\nimport React from "react";\nconst html = htm.bind(React.createElement);\nexport default html;\nexport { html };\n`,
};
for (const [name, src] of Object.entries(entries)) writeFileSync(join(entriesDir, `${name}.mjs`), src);

rmSync(outdir, { recursive: true, force: true });
await build({
  entryPoints: Object.fromEntries(Object.keys(entries).map((n) => [n, join(entriesDir, `${n}.mjs`)])),
  outdir,
  bundle: true,
  splitting: true,
  format: "esm",
  minify: true,
  platform: "browser",
  target: "es2022",
  outExtension: { ".js": ".mjs" },
  chunkNames: "chunk-[hash]",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  absWorkingDir: root,
  logLevel: "warning",
});

// Fonts: Geist (variable, latin) + Geist Mono 400/500/600 (latin).
mkdirSync(fontsDir, { recursive: true });
const geistDir = dirname(require.resolve("@fontsource-variable/geist/package.json"));
const monoDir = dirname(require.resolve("@fontsource/geist-mono/package.json"));
const fonts = [
  [join(geistDir, "files", "geist-latin-wght-normal.woff2"), "geist-latin-wght-normal.woff2"],
  [join(geistDir, "files", "geist-latin-wght-italic.woff2"), "geist-latin-wght-italic.woff2"],
  ...[400, 500, 600].map((w) => [join(monoDir, "files", `geist-mono-latin-${w}-normal.woff2`), `geist-mono-latin-${w}-normal.woff2`]),
];
for (const [from, to] of fonts) {
  if (!existsSync(from)) throw new Error(`build-vendor: missing font ${from}`);
  copyFileSync(from, join(fontsDir, to));
}

const out = readdirSync(outdir).map((f) => `${f} ${(statSync(join(outdir, f)).size / 1024).toFixed(1)}k`);
console.log(`vendor: ${out.join(", ")}\nfonts: ${fonts.map((f) => f[1]).join(", ")}`);
